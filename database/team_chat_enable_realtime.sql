-- Ensure the messages table is published to Supabase Realtime
-- Run this once in Supabase SQL editor if chat messages don't live-update

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    execute 'alter publication supabase_realtime add table public.messages';
  end if;
end $$;